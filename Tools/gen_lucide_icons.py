# Generates Engine/Source/Runtime/UI/Public/UI/Icons.h from the Lucide font's codepoints.json.
# Usage: python Tools/gen_lucide_icons.py
import json, os, re

root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
src = os.path.join(root, 'Engine', 'Content', 'Fonts', 'Lucide', 'codepoints.json')
dst = os.path.join(root, 'Engine', 'Source', 'Runtime', 'UI', 'Public', 'UI', 'Icons.h')
codepoints = json.load(open(src, encoding='utf-8'))

lines = [
    '#pragma once',
    '',
    '// Lucide icons (ISC license, Engine/Content/Fonts/Lucide) as UTF-8 string literals for the icon font.',
    '// Generated by Tools/gen_lucide_icons.py from codepoints.json - do not edit.',
    '//',
    '//   ui::Button(ZX_ICON_SAVE " Save");',
    '',
]
for name in sorted(codepoints):
    cp = codepoints[name]
    macro = 'ZX_ICON_' + re.sub(r'[^A-Z0-9]', '_', name.upper())
    utf8 = chr(cp).encode('utf-8')
    lines.append('#define {} "{}"'.format(macro, ''.join('\\x{:02X}'.format(b) for b in utf8)))
lines.append('')
open(dst, 'w', encoding='utf-8', newline='\n').write('\n'.join(lines))
print('icons:', len(codepoints))
